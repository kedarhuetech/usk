function createTemplate(record) {
  const thumbnail = getThumbnailPath(record.thumbnail);
  const primaryImage = record.primaryImage ? getThumbnailPath(record.primaryImage) : undefined;
  const isQuickPersonalize = Boolean(record.quickPersonalize);
  const common = {
    id: record.id,
    title: record.title,
    name: record.title,
    category: record.category,
    type: record.templateType,
    templateType: record.templateType,
    editMode: isQuickPersonalize ? "quick-personalize" : record.templateType === "flat" ? "overlay-ready" : "quick-customize",
    format: record.format,
    width: record.canvas.width,
    height: record.canvas.height,
    canvas: record.canvas,
    thumbnail,
    thumbnailAlt: `${record.title} marketing template preview`,
    businessCategories: record.businessCategories,
    discoveryTabs: record.discoveryTabs,
    sections: record.sections,
    tags: record.tags,
    assets: {
      thumbnail,
      ...(primaryImage ? { primaryImage } : {}),
      ...(record.assets || {}),
      source: "local-starter-pack",
    },
    brandBindings: record.brandBindings,
    quickPersonalize: record.quickPersonalize || null,
    editableConfig: {
      supportsBrandBindings: record.brandBindings.length > 0,
      supportsUserOverlays: true,
      supportsElementEditing: record.templateType === "editable" || isQuickPersonalize,
      supportsPosterEditing: record.templateType !== "flat",
    },
    eventId: record.eventId,
    eventIds: record.eventIds || [],
  };

  if (record.templateType === "flat") {
    return {
      ...common,
      background: {
        type: "image",
        src: thumbnail,
        locked: true,
        editable: false,
      },
      elements: isQuickPersonalize ? createQuickPersonalizeOverlays(record) : createFlatBrandOverlays(record),
    };
  }

  return {
    ...common,
    background: {
      type: "shape",
      fill: record.category === "Festival" ? "#fff7ed" : record.category === "Food" ? "#fff7ed" : "#eff6ff",
      locked: true,
      editable: false,
    },
    elements: record.elementsFactory ? record.elementsFactory(record) : createEditableElements(record),
  };
}

export const marketingTemplateRegistry = Object.fromEntries(templateRecords.map((record) => [record.id, createTemplate(record)]));

export const marketingTemplates = Object.values(marketingTemplateRegistry);

export function getTemplateById(id) {
  return marketingTemplateRegistry[id] || null;
}

function getCategoryScore(template, businessCategory = "general") {
  const targetTokens = categoryWeights[businessCategory] || categoryWeights.general;
  const searchable = [
    template.category,
    template.title,
    template.format,
    ...template.businessCategories,
    ...template.tags,
    ...template.sections,
  ]
    .join(" ")
    .toLowerCase();

  return targetTokens.reduce((score, token) => score + (searchable.includes(token) ? 1 : 0), 0);
}

export function resolveTemplates(templateIds = []) {
  const seen = new Set();
  return templateIds
    .map((id) => getTemplateById(id))
    .filter(Boolean)
    .filter((template) => {
      if (seen.has(template.id)) return false;
      seen.add(template.id);
      return true;
    });
}

export function resolveDiscoveryTemplates(templateIds = [], options = {}) {
  const templates = resolveTemplates(templateIds);
  const businessCategory = options.businessCategory || "general";

  return [...templates].sort((a, b) => {
    const categoryDelta = getCategoryScore(b, businessCategory) - getCategoryScore(a, businessCategory);
    if (categoryDelta !== 0) return categoryDelta;
    return toTitleCase(a.category).localeCompare(toTitleCase(b.category));
  });
}
