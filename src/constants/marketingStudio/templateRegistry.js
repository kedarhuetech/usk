function toTitleCase(value) {
  return String(value || "")
    .replace(/[-_]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\b\w/g, (letter) => letter.toUpperCase());
}

function getThumbnailPath(fileName) {
  if (!fileName) return "";
  if (/^(https?:|data:|blob:|\/)/.test(fileName)) return fileName;
  return `${ASSET_BASE}/${fileName}`;
}

